#!/usr/bin/env node
// Rewrites the "Downloads" block of README.md from each <app>/latest.json.
// Run after a new APK release (after <app>/latest.json is committed):
//   node scripts/render-readme-table.mjs
// Only the text between the two marker comments in README.md is replaced.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

// Store links only for listings that are live on the App Store (checked via
// itunes.apple.com/lookup + App Store Connect state). Never add a platform here
// before its listing returns an install button.
const STORES = {
  betterkids: { name: 'BetterKids: Learn & Explore', id: '6797240519', ios: true, mac: true },
  storyshort: { name: 'StoryShort AI Video', id: '6797226564', ios: true, mac: true },
  billsai: { name: 'BillsAI Expense Tracker', id: '6759242647', ios: true, mac: false },
  sportmo: { name: 'Sportmo', id: '6836209256', ios: false, mac: false },
  bugsly: { name: 'Bugsly', id: '6799332568', ios: true, mac: true },
};

const mb = (b) => `${(b / 1024 / 1024).toFixed(1)} MB`;
const storeCell = (s) => {
  const links = [];
  if (s.ios) links.push(`[iPhone/iPad](https://apps.apple.com/app/id${s.id})`);
  if (s.mac) links.push(`[Mac](https://apps.apple.com/app/id${s.id}?mt=12)`);
  return links.length ? links.join(', ') : 'not in the App Store yet';
};

const apps = Object.keys(STORES).map((key) => {
  const j = JSON.parse(fs.readFileSync(path.join(root, key, 'latest.json'), 'utf8'));
  return { key, j, s: STORES[key] };
});

let out = '';
out += '| App | Version (build) | Released | Recommended APK (arm64-v8a) | SHA-256 (arm64-v8a) | App Store |\n';
out += '|---|---|---|---|---|---|\n';
for (const { j, s } of apps) {
  const rec = j.files.find((f) => f.recommended) ?? j.files[0];
  out += `| ${s.name} | ${j.version} (${j.versionCode}) | ${j.released} | [${rec.url.split('/').pop()}](${rec.url}) (${mb(rec.bytes)}) | \`${rec.sha256}\` | ${storeCell(s)} |\n`;
}
out += '\n';
for (const { j, s } of apps) {
  out += `<details><summary>${s.name} ${j.version}: all files, release page and checksums</summary>\n\n`;
  out += `Package \`${j.package}\`, Android ${j.minAndroid} or newer, [release page](${j.releaseUrl}), [latest.json](https://raw.githubusercontent.com/airdropfi/app-downloads/main/${apps.find((a) => a.j === j).key}/latest.json).\n\n`;
  out += '| Build | Size | SHA-256 |\n|---|---|---|\n';
  for (const f of j.files) {
    out += `| [${f.abi}](${f.url}) | ${mb(f.bytes)} | \`${f.sha256}\` |\n`;
  }
  out += '\n</details>\n\n';
}

const BEGIN = '<!-- downloads:begin (generated by scripts/render-readme-table.mjs, do not edit by hand) -->';
const END = '<!-- downloads:end -->';
const readmePath = path.join(root, 'README.md');
const readme = fs.readFileSync(readmePath, 'utf8');
const a = readme.indexOf(BEGIN);
const b = readme.indexOf(END);
if (a < 0 || b < 0 || b < a) {
  console.error('README.md is missing the downloads:begin / downloads:end markers');
  process.exit(1);
}
fs.writeFileSync(readmePath, readme.slice(0, a) + BEGIN + '\n' + out.trimEnd() + '\n' + readme.slice(b));
console.log(`README.md updated for ${apps.map((x) => `${x.key} ${x.j.version}`).join(', ')}`);
